// Emits src/palette_chrome.rs from tests/fixtures/paletteCases.json (itself produced by gen.mjs from the
// Electron palette.ts). Run: node tools/fixtures/gen.mjs && node tools/fixtures/gen-palette.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const cases = JSON.parse(readFileSync('tests/fixtures/paletteCases.json', 'utf8'))
const snake = (k) => k.replace(/[A-Z]/g, (c) => '_' + c.toLowerCase())
const chromeKeys = Object.keys(cases[0].chrome)
const borderKeys = Object.keys(cases[0].paneBorder)

let out = '// @generated by tools/fixtures/gen-palette.mjs from renderer/theme/palette.ts. Do not edit.\n'
out += '//! Chrome (window furniture) and pane-border colours, light and dark. Port of `palette.ts`.\n'
out += 'pub struct Chrome {\n' + chromeKeys.map((k) => `    pub ${snake(k)}: &'static str,`).join('\n') + '\n}\n\n'
out += 'pub struct PaneBorders {\n' + borderKeys.map((k) => `    pub ${snake(k)}: &'static str,`).join('\n') + '\n}\n\n'
for (const c of cases) {
  const name = c.name.toUpperCase()
  out += `pub const ${name}_CHROME: Chrome = Chrome {\n` + chromeKeys.map((k) => `    ${snake(k)}: "${c.chrome[k]}",`).join('\n') + '\n};\n\n'
  out += `pub const ${name}_BORDERS: PaneBorders = PaneBorders {\n` + borderKeys.map((k) => `    ${snake(k)}: "${c.paneBorder[k]}",`).join('\n') + '\n};\n\n'
}
writeFileSync('src/palette_chrome.rs', out)
