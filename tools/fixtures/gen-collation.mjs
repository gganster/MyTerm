// Emits src/collate_table.rs: the ICU root-collation weights that `String.prototype.localeCompare`
// uses in 0.5.0 for ASCII and Latin-1/Latin Extended-A letters, read from the Node/ICU build itself.
// Run: node tools/fixtures/gen-collation.mjs > src/collate_table.rs
const base = (a, b) => a.localeCompare(b, undefined, { sensitivity: 'base' })
const ascii = Array.from({ length: 128 }, (_, i) => String.fromCharCode(i))
const ignorable = ascii.filter((c) => ('a' + c + 'b').localeCompare('ab') === 0).map((c) => c.charCodeAt(0))
const visible = ascii.filter((c) => !ignorable.includes(c.charCodeAt(0))).sort((a, b) => base(a, b) || 0)
const primary = new Array(128).fill(255)
let rank = 0
visible.forEach((c, i) => {
  if (i > 0 && base(visible[i - 1], c) !== 0) rank++
  primary[c.charCodeAt(0)] = rank
})

// accented Latin letters: cp -> [base ascii letter, secondary rank of the accent]
const marks = new Set()
const entries = []
for (let cp = 0xa0; cp <= 0x17f; cp++) {
  const d = String.fromCodePoint(cp).normalize('NFD')
  if (d.length === 2 && /[A-Za-z]/.test(d[0]) && /\p{M}/u.test(d[1])) {
    entries.push([cp, d[0], d[1]])
    marks.add(d[1])
  }
}
const sortedMarks = [...marks].sort((a, b) => ('e' + a).localeCompare('e' + b))
const sec = (m) => sortedMarks.indexOf(m) + 1

const out = []
out.push('// @generated by tools/fixtures/gen-collation.mjs from the ICU build of Node. Do not edit.')

out.push(`/// Primary weight per ASCII code point; 255 = ignorable.`)
out.push(`pub const PRIMARY: [u8; 128] = [${primary.join(', ')}];`)
out.push(`/// (code point, base ASCII letter, secondary weight of the accent), sorted by code point.`)
out.push(`pub const ACCENTED: [(u32, char, u8); ${entries.length}] = [`)
for (const [cp, b, m] of entries) out.push(`    (0x${cp.toString(16)}, '${b}', ${sec(m)}),`)
out.push('];')
console.log(out.join('\n'))
