"""Emits src/term/box_table.rs: [left, right, up, down] weights for U+2500..U+257F, from the Unicode
character names. Weights: 0 none, 1 light, 2 heavy, 3 double. Diagonals and arcs are flagged apart.
Run: python tools/fixtures/gen-box.py > src/term/box_table.rs"""
import unicodedata

W = {"LIGHT": 1, "SINGLE": 1, "HEAVY": 2, "DOUBLE": 3}
D = {"LEFT": "l", "RIGHT": "r", "UP": "u", "DOWN": "d"}


def parse(name):
    rest = name.replace("BOX DRAWINGS ", "")
    rest = rest.replace("LIGHT ARC", "LIGHT").replace("DOUBLE DASH", "").replace("TRIPLE DASH", "").replace("QUADRUPLE DASH", "")
    rest = " ".join(rest.split())
    out = {"l": 0, "r": 0, "u": 0, "d": 0}
    if "DIAGONAL" in rest:
        return None
    parts = [p.split() for p in rest.split(" AND ")]
    lead = None
    for p in parts:
        if p[0] in W:
            lead = lead or W[p[0]]
    for p in parts:
        weight, dirs = None, []
        for tok in p:
            if tok in W:
                weight = W[tok]
            elif tok == "HORIZONTAL":
                dirs += ["l", "r"]
            elif tok == "VERTICAL":
                dirs += ["u", "d"]
            elif tok in D:
                dirs.append(D[tok])
        weight = weight or lead or 1
        for d in dirs:
            out[d] = weight
    return out


rows = []
for cp in range(0x2500, 0x2580):
    name = unicodedata.name(chr(cp))
    p = parse(name)
    if p is None:
        rows.append((cp, name, None))
    else:
        rows.append((cp, name, [p["l"], p["r"], p["u"], p["d"]]))

print("// @generated by tools/fixtures/gen-box.py from the Unicode names. Do not edit.")
print("/// [left, right, up, down] weights for U+2500..=U+257F: 0 none, 1 light, 2 heavy, 3 double. Diagonals (U+2571..U+2573) are all zero.")
print("pub const BOX: [[u8; 4]; 128] = [")
for cp, name, w in rows:
    w = w or [0, 0, 0, 0]
    print(f"    [{w[0]}, {w[1]}, {w[2]}, {w[3]}], // U+{cp:04X} {name.replace('BOX DRAWINGS ', '').title()}")
print("];")
